#!/usr/bin/env python3
"""Writes standard.rs: the advance widths of the 14 standard fonts by glyph
name, and the encodings that name their codes, for redaction to place the
glyphs of a standard font that carries no /Widths.

The numbers are Adobe's Core 14 AFM metrics, as hayro-interpret 0.7
(Apache-2.0 OR MIT) generates them from PDFBox's copies; this reads them
from its source in cargo's registry:

    python3 make_standard.py ~/.cargo/registry/src/index.crates.io-*/hayro-interpret-0.7.0
"""
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1]) / "src" / "font" / "generated"
fonts = {}
current = None
for line in (root / "metrics.rs").read_text().splitlines():
    m = re.match(r"pub\(crate\) static (\w+):", line)
    if m:
        current = m.group(1)
        fonts[current] = []
        continue
    m = re.match(r'\s*"([^"]+)" => ([\d.]+)_f32', line)
    if m and current:
        fonts[current].append((m.group(1), int(float(m.group(2)))))


def encoding(name):
    table = [""] * 256
    for line in (root / f"{name}.rs").read_text().splitlines():
        m = re.match(r'\s*(\d+)_u8 => "([^"]+)"', line)
        if m:
            code = int(m.group(1))
            if not table[code]:
                table[code] = m.group(2)
    return table


out = [
    "//! Generated by make_standard.py from hayro-interpret 0.7 (Apache-2.0 OR MIT):",
    "//! Adobe's Core 14 AFM advance widths by glyph name, and the encodings that",
    "//! name a simple font's codes. Do not edit by hand.",
    "",
]
for name, entries in sorted(fonts.items()):
    entries.sort()
    body = ", ".join(f'("{n}", {w})' for n, w in entries)
    out.append(f"pub(super) static {name}: &[(&str, u16)] = &[{body}];")
for name, rust in [("standard", "STANDARD"), ("win_ansi", "WIN_ANSI"), ("mac_roman", "MAC_ROMAN"), ("symbol", "SYMBOL_ENCODING"), ("zapf_dings", "ZAPF_ENCODING")]:
    table = encoding(name)
    body = ", ".join(f'"{n}"' for n in table)
    out.append(f"pub(super) static {rust}: [&str; 256] = [{body}];")
pathlib.Path(__file__).with_name("standard.rs").write_text("\n".join(out) + "\n")
