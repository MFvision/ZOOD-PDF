// Generates src/hijri_table.rs: Umm al-Qura month lengths for 1356–1500 AH (1937–2077 CE).
// Source of the facts: the Umm al-Qura calendar as shipped in ICU (Unicode License v3) through
// Node's Intl ("islamic-umalqura"). Run from the crate: node gen/umalqura.mjs > src/hijri_table.rs
const fmt = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura', { timeZone: 'UTC', year: 'numeric', month: 'numeric', day: 'numeric' });
const parts = (t) =>
  Object.fromEntries(
    fmt
      .formatToParts(new Date(t))
      .filter((p) => p.type !== 'literal')
      .map((p) => [p.type, Number.parseInt(p.value, 10)]),
  );
const FIRST = 1356;
const LAST = 1500;
const DAY = 86400000;
// Julian day number of a UTC midnight timestamp.
const jdn = (t) => Math.round(t / DAY + 2440587.5);
let t = Date.UTC(1937, 0, 1);
const starts = new Map();
for (let i = 0; i < 60000; i++, t += DAY) {
  const p = parts(t);
  if (p.day === 1 && p.year >= FIRST && p.year <= LAST + 1) starts.set(`${p.year}-${p.month}`, jdn(t));
  if (p.year > LAST + 1) break;
}
const first = starts.get(`${FIRST}-1`);
const masks = [];
for (let y = FIRST; y <= LAST; y++) {
  let mask = 0;
  for (let m = 1; m <= 12; m++) {
    const a = starts.get(`${y}-${m}`);
    const b = m === 12 ? starts.get(`${y + 1}-1`) : starts.get(`${y}-${m + 1}`);
    const len = b - a;
    if (len !== 29 && len !== 30) throw new Error(`bad length ${y}/${m}: ${len}`);
    if (len === 30) mask |= 1 << (m - 1);
  }
  masks.push(mask);
}
const rows = [];
for (let i = 0; i < masks.length; i += 8) {
  rows.push('    ' + masks.slice(i, i + 8).map((m) => `0x${m.toString(16).padStart(3, '0')}`).join(', ') + ',');
}
console.log(`//! Umm al-Qura month lengths (generated by \`gen/umalqura.mjs\`; do not edit).
//! Bit \`m - 1\` of a year's mask is set when month \`m\` has 30 days (otherwise 29).
//! Facts from the Umm al-Qura calendar as shipped in ICU (Unicode License v3).

/// First Hijri year in the table.
pub const FIRST_YEAR: i32 = ${FIRST};
/// Julian day number of 1 Muharram ${FIRST} AH.
pub const FIRST_JDN: i64 = ${first};
/// Month-length masks, one per year from [\`FIRST_YEAR\`].
pub const MONTHS: [u16; ${masks.length}] = [
${rows.join('\n')}
];`);
