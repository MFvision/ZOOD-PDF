export const phoneLang: 'ar' | 'en' = typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ar') ? 'ar' : 'en';

export function ps(key: PhoneKey, params?: Record<string, string | number>): string {
  const template = phoneLang === 'ar' ? ar[key] : en[key];
  return params ? template.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m)) : template;
}
