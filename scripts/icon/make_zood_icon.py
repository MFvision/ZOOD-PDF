"""Writes the ZOOD app mark — original artwork for محرر زود PDF.

The mark is a slab **Z**: the initial of ZOOD in Latin, and the stroke of the
Arabic zay. It is drawn as a leaflet folded in a Z — a head, a fold and a
foot, three panels of one gold, each taking the light differently — on a deep
ink ground. Those are the brand's two colours, ink and gold, and nobody
else's. At a glance, and at 40 px, the three panels read as one letter; close
up they read as paper.

Nothing here is traced from, or modelled on, another product's icon.

    python3 scripts/icon/make_zood_icon.py out.svg [options]

      --square      full-bleed square, no rounded corners (iOS: the system
                    cuts its own shape, and an icon with corners of its own
                    shows them inside that shape)
      --maskable    full-bleed, with the mark inside the middle 80 % (the
                    part every home-screen shape keeps)
      --mark-only   the letter alone on transparency, for use on a page
      --dark        the ink ground a shade deeper, for iOS's dark app icon
      --tinted      one grey channel (the letter light, the ground black),
                    for iOS's tinted app icon, which the system colours itself
"""
import math
import sys

OUT = sys.argv[1]
FLAGS = set(sys.argv[2:])
SQUARE = '--square' in FLAGS
MASKABLE = '--maskable' in FLAGS
MARK_ONLY = '--mark-only' in FLAGS
DARK = '--dark' in FLAGS
TINTED = '--tinted' in FLAGS

# ---------------------------------------------------------------- the letter
#
# A 1024 grid. The Z spans 292…732 across and 308…716 down; its bars are 92
# thick and its diagonal is sheared so that its own thickness, measured square
# to it, is a hair under the bars' — which is what keeps a slab Z from looking
# heavy through the middle.
LEFT, RIGHT, TOP, BOTTOM = 292.0, 732.0, 308.0, 716.0
BAR = 92.0
SHEAR = 156.0     # how far apart the diagonal's two edges are, measured across

head_bottom = TOP + BAR
foot_top = BOTTOM - BAR
outer_foot = LEFT + SHEAR      # where the diagonal's upper edge meets the foot
inner_head = RIGHT - SHEAR     # where its lower edge leaves the head


def path(points):
    return 'M' + ' L'.join(f'{x:.1f} {y:.1f}' for x, y in points) + ' Z'


SEAM = 2.0   # the fold reaches this far into the head and the foot, which are
             # drawn over it: two shapes that merely meet leave a light line.

HEAD = path([(LEFT, TOP), (RIGHT, TOP), (RIGHT, head_bottom), (LEFT, head_bottom)])
FOLD = path([
    (inner_head, head_bottom - SEAM), (RIGHT, head_bottom - SEAM),
    (outer_foot, foot_top + SEAM), (LEFT, foot_top + SEAM),
])
FOOT = path([(LEFT, foot_top), (RIGHT, foot_top), (RIGHT, BOTTOM), (LEFT, BOTTOM)])


def squircle(cx, cy, half, n=5.0, steps=256):
    """A continuous-corner square, as the desktop icon's tile is."""
    points = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = cx + half * math.copysign(abs(c) ** (2 / n), c)
        y = cy + half * math.copysign(abs(s) ** (2 / n), s)
        points.append(f'{x:.2f},{y:.2f}')
    return 'M' + ' L'.join(points) + ' Z'


# ---------------------------------------------------------------- the colours
#
# ZOOD's two: ink, a deep blue-black with a little warmth left in it, and a
# gold that is a metal rather than a yellow. Each panel takes its own shade of
# that gold, the head towards the light and the foot away from it. They are
# the same numbers as `ZoodPalette` in apps/ios/PDFEditor/Design/Themes.swift.
INK_TOP, INK_MID, INK_FOOT = ('#2B3560', '#141C39', '#080B1A')
if DARK:
    INK_TOP, INK_MID, INK_FOOT = ('#1A2142', '#0B1024', '#04060F')
GOLD = {
    'head': ('#FAD98C', '#F0C25F'),
    'fold': ('#EEBE58', '#DCA33C'),
    'foot': ('#E0A63A', '#C68420'),
}
if TINTED:
    INK_TOP = INK_MID = INK_FOOT = '#000000'
    GOLD = {
        'head': ('#FFFFFF', '#F2F2F2'),
        'fold': ('#E4E4E4', '#D4D4D4'),
        'foot': ('#C6C6C6', '#B4B4B4'),
    }

body = 'M0 0 H1024 V1024 H0 Z' if (SQUARE or MASKABLE) else squircle(512, 512, 412)
# A maskable icon keeps the letter inside the middle 80 %, which every shape keeps.
open_safe, close_safe = ('<g transform="translate(102.4 102.4) scale(0.8)">', '</g>') if MASKABLE else ('', '')

ground = '' if MARK_ONLY else f'''  <path d="{body}" fill="url(#ink)"/>
  <path d="{body}" fill="url(#sheen)"/>
'''


def ramp(name):
    start, end = GOLD[name]
    return (
        f'    <linearGradient id="{name}" x1="0.05" y1="0" x2="0.75" y2="1">\n'
        f'      <stop offset="0" stop-color="{start}"/>\n'
        f'      <stop offset="1" stop-color="{end}"/>\n'
        f'    </linearGradient>'
    )


svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- ZOOD app mark. Original artwork, Apache-2.0, generated by
     scripts/icon/make_zood_icon.py. A slab Z — ZOOD's initial, and the
     stroke of the Arabic zay — drawn as a leaflet folded in a Z: three
     panels of one gold, each taking the light differently, on ink.
     It copies nobody's icon. -->
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <linearGradient id="ink" x1="0.1" y1="0" x2="0.9" y2="1">
      <stop offset="0" stop-color="{INK_TOP}"/>
      <stop offset="0.52" stop-color="{INK_MID}"/>
      <stop offset="1" stop-color="{INK_FOOT}"/>
    </linearGradient>
    <radialGradient id="sheen" cx="0.5" cy="0.02" r="0.8">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0.18"/>
      <stop offset="1" stop-color="#ffffff" stop-opacity="0"/>
    </radialGradient>
{ramp('head')}
{ramp('fold')}
{ramp('foot')}
  </defs>

{ground}  {open_safe}<g>
    <path d="{FOLD}" fill="url(#fold)"/>
    <path d="{HEAD}" fill="url(#head)"/>
    <path d="{FOOT}" fill="url(#foot)"/>
  </g>{close_safe}
</svg>
'''

with open(OUT, 'w', encoding='utf-8') as handle:
    handle.write(svg)
print(OUT)
