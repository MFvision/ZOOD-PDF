def block_truth(block) -> list[str]:
    kind = block[0]
    if kind in ("h1", "h2", "h3", "p"):
        return [block[1]]
    if kind == "ul":
        return list(block[1])
    if kind == "ol":
        return [f"{i}. {item}" for i, item in enumerate(block[1], 1)]
    if kind == "ol-ar":
        digits = "٠١٢٣٤٥٦٧٨٩"
        out = []
        for i, item in enumerate(block[1], 1):
            marker = "".join(digits[int(d)] for d in str(i)) + "."
            out.append(f"{marker} {item}")
        return out
    if kind == "table":
        return [" ".join(row) for row in block[1]]
    if kind == "cols":
        out = []
        for b in block[1]:
            out.extend(block_truth(b))
        return out
    raise ValueError(kind)


def doc_truth(blocks) -> str:
    lines = []
    for b in blocks:
        lines.extend(block_truth(b))
    return "\n".join(lines) + "\n"
